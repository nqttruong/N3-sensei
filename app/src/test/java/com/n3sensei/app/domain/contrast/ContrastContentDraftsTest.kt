package com.n3sensei.app.domain.contrast

import com.n3sensei.app.data.importing.ContrastPackCheck
import com.n3sensei.app.domain.contrast.validation.ContrastIssueCode
import com.n3sensei.app.domain.contrast.validation.ContrastSeverity
import com.n3sensei.app.domain.contrast.validation.ValidationMode
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * The Contrast Lab content drafts (tools/content/contrast/drafts, generated by drafts_tool.py) through
 * the app's own parser + validator, and every question through the app's grader:
 * - the TEST-ONLY pack built from the drafts has no ERROR in the Kotlin validator (same rules as Python);
 * - every question has exactly one correct option, every other option grades INCORRECT;
 * - every group has the four question types and two examples per item;
 * - no draft is APPROVED or PUBLISHED (nobody has reviewed them) and no pack is in the app's assets.
 */
class ContrastContentDraftsTest {

    private val root = ContrastFixtures.repoRoot
    private val testPack = File(root, "app/src/androidTest/assets/contrast/test-pack-n3-unreviewed.json")
    private val drafts = File(root, "tools/content/contrast/drafts")

    private val pack by lazy {
        val result = ContrastPackCheck.check(testPack.readText(), ValidationMode.IMPORT).validation
        assertFalse(result.issues.filter { it.severity == ContrastSeverity.ERROR }.joinToString { "${it.code} ${it.path}" }, result.hasErrors)
        assertTrue("every warning of the TEST-ONLY pack is listed", result.unacknowledgedWarnings.isEmpty())
        assertTrue(result.issues.filter { it.severity == ContrastSeverity.WARNING }.all { it.code == ContrastIssueCode.FURIGANA_MISSING })
        assertNotNull(result.pack)
        result.pack!!
    }

    @Test
    fun theTestPack_passesTheKotlinValidator_with69Groups() {
        assertEquals(69, pack.groups.size)
        val byType = pack.groups.groupingBy { it.detail.group.contentType }.eachCount()
        assertEquals(mapOf(ContrastContentType.GRAMMAR to 22, ContrastContentType.VOCABULARY to 24, ContrastContentType.KANJI to 23), byType)
    }

    @Test
    fun everyQuestion_hasExactlyOneCorrectAnswer_forTheAppGrader() {
        var graded = 0
        pack.groups.flatMap { it.questions }.forEach { q ->
            val outcomes = q.options.map { ContrastAnswerChecker.grade(q, AnswerInput.Chosen(it.id)).outcome }
            assertEquals(q.id, 1, outcomes.count { it == AnswerOutcome.CORRECT })
            assertEquals(q.id, AnswerOutcome.CORRECT, ContrastAnswerChecker.grade(q, AnswerInput.Chosen(q.correctOptionId)).outcome)
            assertEquals(q.id, AnswerOutcome.SKIPPED, ContrastAnswerChecker.grade(q, AnswerInput.Skipped).outcome)
            if (q.type == ContrastQuestionType.ERROR_DETECTION) {
                assertEquals(q.id, q.prompt!!.japanese, q.options.joinToString("") { it.text })
                assertEquals(q.id, q.targetItemId, q.correction!!.itemId)
            } else {
                assertEquals(q.id, q.targetItemId, q.correctOption.itemId)
            }
            if (q.type == ContrastQuestionType.FILL_IN_THE_BLANK) assertEquals(q.id, 1, Regex("＿＿＿").findAll(q.prompt!!.japanese).count())
            graded++
        }
        assertEquals(277, graded)
    }

    @Test
    fun everyGroup_hasTheFourTypes_twoExamplesPerItem_andExplanations() {
        pack.groups.forEach { g ->
            val id = g.detail.group.id
            assertEquals(id, ContrastQuestionType.entries.toSet(), g.questions.map { it.type }.toSet())
            g.detail.items.forEach { item -> assertTrue("$id ${item.id}", g.detail.examples.count { it.itemId == item.id } >= 2) }
            assertTrue(id, g.detail.theory.size >= 2 && g.detail.comparison.size >= 2 && g.detail.memoryTips.isNotEmpty() && g.detail.commonMistakes.isNotEmpty())
            assertTrue(id, g.questions.all { it.explanationVi.isNotBlank() })
        }
    }

    @Test
    fun theDraftsAreUnreviewed_andNoPackIsInTheAppAssets() {
        val files = drafts.listFiles { f -> f.extension == "json" }.orEmpty()
        assertEquals(69, files.size)
        files.forEach { f ->
            val tree = Json.parseToJsonElement(f.readText()).jsonObject
            assertEquals(f.name, "AI_GENERATED", tree.getValue("status").jsonPrimitive.content)
            assertFalse(f.name, "approval" in tree)
        }
        val assets = File(root, "app/src/main/assets").walkTopDown().filter { it.isFile }.map { it.name }.toList()
        assertTrue(assets.toString(), assets.none { it.startsWith("contrast") })
    }
}
